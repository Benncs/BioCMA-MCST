#include <biocma_cst_config.hpp>
#include <core/init_rng_seed.hpp>
#include <mc/prng/prng.hpp>
#ifndef NO_MPI
#  include <mpi_w/wrap_mpi.hpp>
#endif

namespace Core
{

  uint64_t
  get_rng_seed([[maybe_unused]] const ExecInfo& info)
  {
    uint64_t seed = MC::master_seed();
    if constexpr (AutoGenerated::FlagCompileTime::use_mpi)
    {
#ifndef NO_MPI
      const auto master_seed = WrapMPI::broadcast(seed, 0);
      uint64_t tmp = master_seed + static_cast<uint64_t>(info.current_rank);
      seed = MC::next_splitmix64(tmp);
#else
      __builtin_unreachable();
      throw std::runtime_error("ERROR MPI activate but not implemented ");
#endif
    }
    return seed;
  }
} // namespace Core
